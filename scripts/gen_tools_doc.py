"""Generate docs/tools.md from the tool registry by running each tool on an example.

The Cypher shown is exactly what the tool executed (from its cypher_trace), so the docs
cannot drift from the code. Usage: python scripts/gen_tools_doc.py [graph_name]
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.tools.base import reset_trace  # noqa: E402
from src.tools.registry import TOOLS, call_tool  # noqa: E402

EXAMPLES = {
    "trace_decision": {"kep_or_query": "KEP-3063"},
    "who_owns": {"target": "kubelet"},
    "who_knows": {"topic": "sidecar containers"},
    "impact_of": {"entity": "KEP-753"},
    "timeline": {"kep": "KEP-753"},
    "what_changed": {"since": "2026-09-01", "team": "sig-node"},
    "connect": {"a": "derekwaynecarr", "b": "KEP-753"},
    "influence": {"metric": "pagerank", "limit": 5},
    "resolve": {"text": "graceful node shutdown"},
}
OUT = Path(__file__).resolve().parents[1] / "docs" / "tools.md"


def main(graph_name: str) -> None:
    lines = ["# Graph tools and their Cypher", "",
             "The agent can only act through these tools. Each one is a fixed set of parameterized Cypher queries "
             "(the LLM never writes Cypher), resolves names against the graph before traversing, and returns "
             "`{data, notes, sources, path, cypher_trace, as_of, stale_flags, found}`. "
             f"Generated by `scripts/gen_tools_doc.py` from graph `{graph_name}`: the queries below are exactly "
             "what each tool ran for its example.", ""]
    for name, spec in TOOLS.items():
        reset_trace()
        args = EXAMPLES[name]
        result = call_tool(name, args, graph_name=graph_name)
        props = spec["schema"]["properties"]
        required = set(spec["schema"].get("required", []))
        lines += [f"## `{name}`", "", spec["description"], "",
                  "| Argument | Type | Required |", "|---|---|---|"]
        lines += [f"| `{a}` | {p.get('type')} | {'yes' if a in required else 'no'} |" for a, p in props.items()]
        lines += ["", f"Example: `{json.dumps(args)}`. Ran {len(result['cypher_trace'])} queries in "
                      f"{sum(c['ms'] for c in result['cypher_trace']):.1f} ms total.", "", "```cypher"]
        seen = set()
        for c in result["cypher_trace"]:
            if c["cypher"] not in seen:
                seen.add(c["cypher"])
                lines += [f"// {c['tool']}: {c['rows']} rows, {c['ms']} ms", c["cypher"], ""]
        data = json.dumps(result["data"], default=str, indent=1)
        lines += ["```", "", "<details><summary>Example output (data)</summary>", "", "```json",
                  data[:2500] + ("\n..." if len(data) > 2500 else ""), "```", "</details>", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(TOOLS)} tools)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "brain_eval")
