"""Human audit of the extraction, and eval/extraction_report.md.

1. `audit` writes eval/extraction_audit.csv: 20 random decisions (fixed seed) plus every KEP in the
   gold set, with blank `verdict` (right / partly / wrong) and `note` columns. A person fills them
   in by reading the KEP's sources; the LLM never grades itself. Existing verdicts are kept.
2. `report` counts quote checks, verified decisions, cost, the audit verdicts and the supersession
   review, and writes eval/extraction_report.md.

Usage: python -m src.extract.report audit | report
"""
import csv
import json
import random
import sys
from pathlib import Path

from src.extract.run import CACHE, PRICE

ROOT = Path(__file__).resolve().parents[2]
DECISIONS = ROOT / "data" / "seed" / "decisions.jsonl"
AUDIT = ROOT / "eval" / "extraction_audit.csv"
GOLD = ROOT / "eval" / "gold_decisions.csv"
REVIEW = ROOT / "eval" / "supersession_review.csv"
REPORT = ROOT / "eval" / "extraction_report.md"
FIELDS = ["kep", "sample", "status", "summary", "rationale", "outcome_reason", "kep_url", "evidence_urls", "verdict", "note"]


def _decisions() -> dict:
    return {d["kep"]: d for d in map(json.loads, DECISIONS.open())}


def _csv(path: Path) -> list[dict]:
    return list(csv.DictReader(path.open())) if path.exists() else []


def audit() -> None:
    decs = _decisions()
    from eval.gold import load as load_gold
    gold = [r["kep"] for r in load_gold()]
    sample = random.Random(42).sample(sorted(decs, key=lambda k: int(k.split("-")[1])), 20)
    previous = {r["kep"]: r for r in _csv(AUDIT)}
    from src.brain.db import graph
    g = graph("brain_eval")
    urls = dict(g.query("MATCH (c:Comment) WHERE c.id IN $ids RETURN c.id, c.url",
                        {"ids": [e["ref"] for d in decs.values() for e in d["evidence"] if e["ref"] != "readme"]}).result_set)
    kep_urls = dict(g.query("MATCH (k:KEP) RETURN k.id, k.readme_url").result_set)
    rows = []
    for kep, why in [(k, "random") for k in sample] + [(k, "gold") for k in gold if k not in sample and k in decs]:
        d, prev = decs[kep], previous.get(kep, {})
        rows.append({"kep": kep, "sample": why, "status": d["outcome"], "summary": d["summary"],
                     "rationale": d["rationale"], "outcome_reason": d["outcome_reason"] or "",
                     "kep_url": kep_urls.get(kep) or "",
                     "evidence_urls": " ".join(dict.fromkeys(urls.get(e["ref"], kep_urls.get(kep) or "")
                                                             for e in d["evidence"])),
                     "verdict": prev.get("verdict", ""), "note": prev.get("note", "")})
    with AUDIT.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    print(f"{len(rows)} rows -> {AUDIT.relative_to(ROOT)} ({len(sample)} random, {len(rows) - len(sample)} gold)")


def report() -> None:
    decs = list(_decisions().values())
    ev_t, ev_p = sum(d["evidence_total"] for d in decs), sum(d["evidence_passed"] for d in decs)
    cost, tok = 0.0, [0, 0]
    for p in CACHE.glob("KEP-*.json"):
        r = json.loads(p.read_text())
        tok[0] += r["usage"]["input"]
        tok[1] += r["usage"]["output"]
        cost += (r["usage"]["input"] * PRICE[r["mode"]][0] + r["usage"]["output"] * PRICE[r["mode"]][1]) / 1e6
    audit_rows = [r for r in _csv(AUDIT) if r["verdict"].strip()]
    verdicts = {v: sum(r["verdict"].strip().lower() == v for r in audit_rows) for v in ("right", "partly", "wrong")}
    review = _csv(REVIEW)
    sup = {v: sum(r["verdict"].strip().lower() == v for r in review) for v in ("yes", "no")}
    conf = {c: sum(d["confidence"] == c for d in decs) for c in ("high", "medium", "low")}
    ok = verdicts["right"] + verdicts["partly"]
    lines = [
        "# Extraction report", "",
        "Generated by `python -m src.extract.report report`. The LLM (Claude Haiku 5.5) writes only the rationale; "
        "the outcome always comes from `kep.yaml` history in the graph. Quotes are checked word for word by code; "
        "the audit verdicts below are written by a person, never by the LLM.", "",
        "## Automatic checks", "",
        "| Measure | Value | Target |", "|---|---|---|",
        f"| Decisions extracted | {len(decs)} | |",
        f"| Evidence quotes found word for word in the cited source | {ev_p}/{ev_t} ({100 * ev_p / max(ev_t, 1):.1f}%) | ≥95% |",
        f"| Decisions with every quote passing | {sum(d['verified'] for d in decs)}/{len(decs)} | |",
        f"| Confidence high / medium / low | {conf['high']} / {conf['medium']} / {conf['low']} | |",
        f"| Tokens in / out | {tok[0]:,} / {tok[1]:,} | |",
        f"| Cost | ${cost:.2f} | budget $5 total |", "",
        "## Human audit", "",
        f"Rows audited: {len(audit_rows)} of {len(_csv(AUDIT))} in `eval/extraction_audit.csv` "
        "(20 random decisions, seed 42, plus the gold KEPs). Method: the participant graded every row against the "
        "KEP's design doc and the quoted comments; AI helped word some of the notes. Verdict scale: right, partly, wrong.", "",
        "| Verdict | Count |", "|---|---|",
        *[f"| {v} | {n} |" for v, n in verdicts.items()],
        f"| right or partly right | {100 * ok / max(len(audit_rows), 1):.0f}% (target ≥80%) |", "",
        *([f"With {len(audit_rows)} rows and no 'wrong' verdict, the 95% upper bound on the share of wrong "
           f"rationales is about {300 / len(audit_rows):.1f}% (rule of three): a small sample, not proof of zero errors."]
          if audit_rows and verdicts["wrong"] == 0 else []), "",
        "## LLM-proposed supersessions", "",
        f"{len(review)} claims not already in `kep.yaml` (`eval/supersession_review.csv`): "
        f"{sup['yes']} confirmed, {sup['no']} rejected, {len(review) - sup['yes'] - sup['no']} not reviewed yet. "
        "Unreviewed claims load as `verified:false` and the agent must hedge on them.", ""]
    REPORT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    {"audit": audit, "report": report}[sys.argv[1]]()
